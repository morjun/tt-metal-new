def block(arms, mode, baseline, sweep, note):
    text = table(arms, mode, baseline) if arms else f"**Knobs** (measurement: {mode}; baseline: {baseline}):"
    if sweep:
        text += f"\n- {sweep}"
    if note:
        text += f"\n- {note}"
    return f"<!-- knobs -->\n{text}\n<!-- /knobs -->\n"


def apply(path, sections):
    s = path.read_text()
    s = re.sub(r"<!-- knobs -->\n.*?<!-- /knobs -->\n\n?", "", s, flags=re.S)
    for heading, spec in sections.items():
        i = s.find(heading + "\n")
        if i < 0:
            raise SystemExit(f"{path.name}: heading not found: {heading}")
        j = i + len(heading) + 1
        q = s.find("**Question.**", j)
        nxt = s.find("\n## ", j)
        if q >= 0 and (nxt < 0 or q < nxt):
            j = s.find("\n\n", q) + 2  # after the Question paragraph
        else:
            j = s.find("\n", j) + 1 if s[j] == "\n" else j
        s = s[:j] + block(*spec) + "\n" + s[j:]
    path.write_text(s)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--record-dir", type=Path, default=REC)
    a = p.parse_args()
    apply(a.record_dir / "09.2a_dram_fed.md", SECTIONS_A)
    apply(a.record_dir / "09.2b_pin_values.md", SECTIONS_B)
    print("ok")


if __name__ == "__main__":
    main()
